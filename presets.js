export const STYLE_IDS = PRESETS.map((s) => s.id);

export function findStyle(key) {
  const raw = String(key ?? '').trim().toLowerCase();
  if (!raw) return undefined;
  const byId = PRESETS.find((s) => s.id === raw);
  if (byId) return byId;
  const byIndex = PRESETS.find((s) => String(s.index) === raw || String(s.index).padStart(2, '0') === raw);
  if (byIndex) return byIndex;
  const byZh = PRESETS.find((s) => s.zh === raw || s.en.toLowerCase() === raw);
  if (byZh) return byZh;
  return PRESETS.find((s) => s.id.includes(raw) || s.zh.includes(raw) || s.en.toLowerCase().includes(raw));
}

